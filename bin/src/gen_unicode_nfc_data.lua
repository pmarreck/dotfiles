#!/usr/bin/env luajit

-- Generate unicode_nfc_data.lua (the tables unicode_nfc.lua needs) from a
-- Unicode Character Database directory:
--   luajit bin/src/gen_unicode_nfc_data.lua "$UNICODE_UCD_DIR" > bin/src/unicode_nfc_data.lua
-- Output is deterministic (sorted by code point) so the test suite can compare
-- the committed file against a fresh generation.

local ucd = arg[1]
if not ucd or ucd == "" then
	io.stderr:write("usage: gen_unicode_nfc_data.lua UCD_DIR\n")
	os.exit(2)
end

local ccc, raw = {}, {}
for line in io.lines(ucd .. "/UnicodeData.txt") do
	local fields = {}
	for field in (line .. ";"):gmatch("([^;]*);") do fields[#fields + 1] = field end
	local cp = tonumber(fields[1], 16)
	local class = tonumber(fields[4])
	if class ~= 0 then ccc[cp] = class end
	local decomposition = fields[6]
	-- Compatibility mappings start with a <tag>; NFC uses canonical ones only.
	if decomposition ~= "" and decomposition:sub(1, 1) ~= "<" then
		local seq = {}
		for h in decomposition:gmatch("%x+") do seq[#seq + 1] = tonumber(h, 16) end
		raw[cp] = seq
	end
end

local version
local excluded = {}
for line in io.lines(ucd .. "/DerivedNormalizationProps.txt") do
	version = version or line:match("^# DerivedNormalizationProps%-([%d.]+)%.txt")
	local first, last, prop = line:match("^(%x+)%.%.(%x+)%s*;%s*([%w_]+)")
	if not first then
		first, prop = line:match("^(%x+)%s*;%s*([%w_]+)")
		last = first
	end
	if prop == "Full_Composition_Exclusion" then
		for cp = tonumber(first, 16), tonumber(last, 16) do excluded[cp] = true end
	end
end
assert(version, "DerivedNormalizationProps.txt has no version header")

local function full_decomposition(cp, out)
	local seq = raw[cp]
	if not seq then
		out[#out + 1] = cp
		return out
	end
	for _, c in ipairs(seq) do full_decomposition(c, out) end
	return out
end

local function sorted_keys(t)
	local keys = {}
	for k in pairs(t) do keys[#keys + 1] = k end
	table.sort(keys)
	return keys
end

local function hexlist(seq)
	local parts = {}
	for i, c in ipairs(seq) do parts[i] = string.format("0x%04X", c) end
	return table.concat(parts, ",")
end

local out = {}
local function emit(s) out[#out + 1] = s end

emit("-- Generated by gen_unicode_nfc_data.lua from the Unicode Character Database " .. version .. ". Do not edit.")
emit("-- ccc: nonzero canonical combining classes.")
emit("-- decomp: full canonical decompositions (Hangul syllables are algorithmic).")
emit("-- pairs: primary composites and the two code points that compose to each.")
emit("return {")
emit('\tversion = "' .. version .. '",')
emit("\tccc = {")
for _, cp in ipairs(sorted_keys(ccc)) do
	emit(string.format("\t\t[0x%04X]=%d,", cp, ccc[cp]))
end
emit("\t},")
emit("\tdecomp = {")
for _, cp in ipairs(sorted_keys(raw)) do
	emit(string.format("\t\t[0x%04X]={%s},", cp, hexlist(full_decomposition(cp, {}))))
end
emit("\t},")
emit("\tpairs = {")
for _, cp in ipairs(sorted_keys(raw)) do
	if not excluded[cp] then
		assert(#raw[cp] == 2, string.format("primary composite U+%04X does not decompose to a pair", cp))
		emit(string.format("\t\t[0x%04X]={%s},", cp, hexlist(raw[cp])))
	end
end
emit("\t},")
emit("}")
io.write(table.concat(out, "\n"), "\n")
